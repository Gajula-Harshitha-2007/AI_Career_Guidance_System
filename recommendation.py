# Maximum possible score for each career before the
# interest bonus is applied.
CAREER_MAX_SCORES = {

    "Software Developer": 25,

    "AI / Machine Learning Engineer": 30,

    "Data Scientist": 30,

    "UI/UX Designer": 30,

    "Cybersecurity Analyst": 30,

    "Business Analyst": 30
}


# ==================================================
# RECOMMENDATION FUNCTION
# ==================================================

def recommend_career(
    interest,
    programming,
    problem_solving,
    mathematics,
    ai_interest,
    design,
    security,
    communication
):

    interest = interest.lower().strip()

    # =========================
    # CAREER SCORES
    # =========================

    scores = {

        "Software Developer":
            (programming * 2)
            +
            (problem_solving * 2)
            +
            mathematics,

        "AI / Machine Learning Engineer":
            (programming * 2)
            +
            mathematics
            +
            (ai_interest * 2)
            +
            problem_solving,

        "Data Scientist":
            (mathematics * 2)
            +
            problem_solving
            +
            (ai_interest * 2)
            +
            programming,

        "UI/UX Designer":
            (design * 3)
            +
            (communication * 2)
            +
            problem_solving,

        "Cybersecurity Analyst":
            (security * 3)
            +
            programming
            +
            (problem_solving * 2),

        "Business Analyst":
            (communication * 3)
            +
            mathematics
            +
            problem_solving
    }


    # =========================
    # INTEREST BONUS
    # =========================

    interest_bonus = {

        "programming":
            "Software Developer",

        "art":
            "UI/UX Designer",

        "design":
            "UI/UX Designer",

        "art and design":
            "UI/UX Designer",

        "art_design":
            "UI/UX Designer",

        "art & design":
            "UI/UX Designer",

        "data":
            "Data Scientist",

        "data science":
            "Data Scientist",

        "artificial intelligence":
            "AI / Machine Learning Engineer",

        "ai":
            "AI / Machine Learning Engineer",

        "machine learning":
            "AI / Machine Learning Engineer",

        "cybersecurity":
            "Cybersecurity Analyst",

        "security":
            "Cybersecurity Analyst",

        "business":
            "Business Analyst",

        "business and management":
            "Business Analyst",

        "business_management":
            "Business Analyst"
    }


    if interest in interest_bonus:

        selected_career = interest_bonus[interest]

        scores[selected_career] += 3


    # =========================
    # RECOMMENDED CAREER
    # =========================

    recommended_career = max(
        scores,
        key=scores.get
    )


    details = CAREER_DETAILS[
        recommended_career
    ]


    # Calculate normalized match percentages.
    match_percentages = get_match_percentages(scores)


    return (
        recommended_career,
        scores,
        details,
        match_percentages
    )


# ==================================================
# MATCH PERCENTAGES
# ==================================================

def get_match_percentages(scores):

    match_percentages = {}

    for career_name, score in scores.items():

        maximum_score = CAREER_MAX_SCORES[career_name]

        percentage = round(
            (score / maximum_score) * 100
        )

        # Keep percentage within 0-100.
        percentage = max(
            0,
            min(100, percentage)
        )

        match_percentages[career_name] = percentage

    return match_percentages


# ==================================================
# TOP 5 CAREERS
# ==================================================

def get_top_careers(scores):

    match_percentages = get_match_percentages(scores)

    sorted_careers = sorted(
        scores.items(),
        key=lambda item: item[1],
        reverse=True
    )


    top_careers = []


    for rank, (career_name, score) in enumerate(
        sorted_careers[:5],
        start=1
    ):

        top_careers.append({

            "rank":
                rank,

            "name":
                career_name,

            "score":
                score,

            "percentage":
                match_percentages[career_name],

            "details":
                CAREER_DETAILS[career_name]

        })


    return top_careers